#!/bin/bash
# Entrypoint of the follower node container (tools/allocator/docker/node/).
# Mirrors logos-blockchain/deployment/scripts/run_node.sh, plus the one-time
# config generation that stack does through its setup container:
#   1. deployment: the image's blockchain_module carries the deployment of
#      its release built in (start with an empty deployment path uses it), so
#      the follower is on the miner's chain by running the miner's image tag.
#      A node/deployment.yaml (the miner's /node-data/deployment.yaml) is
#      copied onto the volume and used instead when present.
#   2. /node-data/0/user_config.yaml is generated by the module itself
#      (blockchain_module.generate_user_config) with MINER_PEERS as
#      initial_peers, the API on 0.0.0.0:18080 (published on the host's
#      loopback by compose) and the swarm on NODE_NET_PORT; regenerated when
#      those inputs change (recorded in /node-data/0/gen.args).
#   3. prolonged_bootstrap_period 3600 s -> 5 s: during that period the
#      node reports lib_slot 0 and the verifier rejects every claim as
#      "not final yet".
#   4. start; then keep the container alive while the daemon lives, so
#      compose restarts it when the daemon dies.
set -u

DATA=/node-data
NODE_DIR="$DATA/0"
CFG="$NODE_DIR/user_config.yaml"
DEP="$DATA/deployment.yaml"
ETC=/etc/allocator-node
NET_PORT="${NODE_NET_PORT:-3000}"
PEERS="${MINER_PEERS:-}"
export LOGOSCTL_CONFIG_DIR=/opt/logos-session LOG_BACKEND=file LOG_DIR="$NODE_DIR/"

say() { printf '[follower %s] %s\n' "$(date -u +%H:%M:%S)" "$*" >&2; }
die() { say "FATAL: $*"; exit 1; }
# logosctl --json call prints {"method","module","result","status"}; the
# module's result is {"success","error","value"}.
call_ok() {
    python3 -I -c '
import json, sys
for line in sys.stdin:
    line = line.strip()
    if not line.startswith("{"):
        continue
    try:
        d = json.loads(line)
    except Exception:
        continue
    r = d.get("result")
    if isinstance(r, str):
        try: r = json.loads(r)
        except Exception: pass
    ok = d.get("status") == "ok" and (not isinstance(r, dict) or r.get("success", True))
    sys.stdout.write(line + "\n")
    sys.exit(0 if ok else 1)
sys.exit(1)'
}

[ -n "$PEERS" ] || die "MINER_PEERS is empty (node.env)"
mkdir -p "$NODE_DIR"

# --- 1. deployment file (optional)
if [ -s "$ETC/deployment.yaml" ]; then
    cp "$ETC/deployment.yaml" "$DEP"
    say "deployment: $ETC/deployment.yaml"
else
    rm -f "$DEP"; DEP=""
    say "deployment: the image's built-in one (no node/deployment.yaml)"
fi

# --- daemon + module
logosctl daemon start --detach >/dev/null 2>&1
i=0
until logosctl daemon status >/dev/null 2>&1; do
    i=$((i + 1)); [ "$i" -lt 60 ] || die "logosctl daemon did not come up"
    sleep 1
done
logosctl module load blockchain_module >/dev/null || die "module load failed"

# --- 2. user config (generate once per set of inputs)
GEN_ARGS=$(python3 -I -c '
import json, sys
peers = [p.strip() for p in sys.argv[1].split(",") if p.strip()]
print(json.dumps({"output": "/node-data/0/user_config.yaml", "net_port": int(sys.argv[2]),
                  "blend_port": 3400, "http_addr": "0.0.0.0:18080", "initial_peers": peers,
                  "state_path": "/node-data/0/state", "storage_path": "/node-data/0/db",
                  "logs_path": "/node-data/0/logs"}, separators=(",", ":")))' "$PEERS" "$NET_PORT")
if [ ! -s "$CFG" ] || [ "$(cat "$NODE_DIR/gen.args" 2>/dev/null)" != "$GEN_ARGS" ]; then
    say "generating $CFG (peers: $PEERS, swarm udp/$NET_PORT)"
    rm -f "$CFG" "$NODE_DIR/keystore.yaml"
    logosctl --json call blockchain_module generate_user_config "$GEN_ARGS" | call_ok >/dev/null \
        || die "generate_user_config failed"
    # --- 3. bootstrap period
    n=$(grep -c "prolonged_bootstrap_period: '3600.000000000'" "$CFG")
    [ "$n" = 1 ] || die "expected exactly one prolonged_bootstrap_period line in the generated config, found $n"
    sed -i "s/prolonged_bootstrap_period: '3600.000000000'/prolonged_bootstrap_period: '5.000000000'/" "$CFG"
    printf '%s' "$GEN_ARGS" > "$NODE_DIR/gen.args"
    chmod 600 "$NODE_DIR/keystore.yaml" "$CFG"
else
    say "reusing $CFG"
fi

# --- 4. start
# The first start right after an unclean stop has failed once here (the
# previous container's daemon had just been killed; the retry 10 s later
# succeeded), so one retry before giving the container back to compose.
start_node() {
    local out
    out=$(logosctl --json call blockchain_module start "$CFG" "$DEP" 2>&1 | call_ok) && return 0
    say "blockchain_module.start answered: ${out:-<nothing>}"
    return 1
}
say "start $CFG '${DEP}'"
if ! start_node; then
    say "retrying start in 10 s"
    sleep 10
    start_node || die "blockchain_module.start failed twice"
fi
i=0
until curl -sf -m 3 http://127.0.0.1:18080/cryptarchia/info >/dev/null 2>&1; do
    i=$((i + 1)); [ "$i" -lt 90 ] || die "API never answered on 18080 (see $NODE_DIR/logs)"
    sleep 2
done
say "API up; peer $(curl -s -m 3 http://127.0.0.1:18080/network/info | python3 -I -c 'import json,sys; d=json.load(sys.stdin); print(d.get("peer_id"))')"
say "info $(curl -s -m 3 http://127.0.0.1:18080/cryptarchia/info)"

stop() { say "stopping"; logosctl daemon stop >/dev/null 2>&1; exit 0; }
trap stop TERM INT
while logosctl daemon status >/dev/null 2>&1; do
    sleep 15 & wait $!
done
die "daemon gone"
