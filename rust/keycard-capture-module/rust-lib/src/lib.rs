// The keycard scheme's PRODUCER for gifted RLN registration: the physical
// card signs the binding digest through IDENTIFY_CARD over PC/SC. Kept apart
// from rln-sign-module so a client without a reader never links pcsclite,
// and from the gifter side so a headless allocator never does either.
// FEATURE: RLN membership gifter keycard capture module (client-side PC/SC)

use keycard_client::reader_card_present;
use rln_auth_vector::{dispatch_produce, ProduceRegistry};
use rln_auth_vectors::claimant::{AllowlistClaimant, AttestationClaimant};
use rln_auth_vectors::signer::KeycardSigner;
use serde_json::json;

// OWNERSHIP: the generated host keeps the instance in a process-lifetime any-box, so the module owns all its data.
pub trait KeycardCaptureModule: Send + 'static {
    /// rln_auth_vector PRODUCE_METHOD for `keycard-allowlist` and
    /// `keycard-attestation`: IDENTIFY_CARD bound to the request's binding
    /// (the card only proves the holder owns a genuine card — the identity
    /// comes from the caller). IDENTIFY_CARD is a public plain-channel
    /// command — no pairing, no PIN. One JSON-string arg (ProduceRequest) →
    /// `{"payload_hex"}` or `{"error"}`.
    fn produce_auth(&mut self, args_json: String) -> String;
    /// Is a Keycard present at the reader? `{present}` — no card session.
    fn card_status(&mut self) -> String;
    fn on_context_ready(&mut self, _ctx: &RustModuleContext) {}
}

// The generated scaffold lives in its own module so its lint expectations
// cover nothing hand-written; the crate root re-exports its public items.
#[expect(
    clippy::absurd_extreme_comparisons,
    clippy::get_first,
    clippy::len_zero,
    clippy::not_unsafe_ptr_arg_deref,
    dead_code,
    unused_comparisons,
    reason = "generated by logos-lidl-gen"
)]
mod generated {
    use super::KeycardCaptureModule;

    include!(concat!(
        env!("CARGO_MANIFEST_DIR"),
        "/generated/provider_gen.rs"
    ));
}
pub use generated::*;

struct KeycardCapture {
    registry: ProduceRegistry,
}

impl Default for KeycardCapture {
    fn default() -> Self {
        Self {
            registry: ProduceRegistry::new()
                .signer(KeycardSigner)
                .claimant(AllowlistClaimant)
                .claimant(AttestationClaimant),
        }
    }
}

impl KeycardCaptureModule for KeycardCapture {
    // Return a plain String (not Result): the codegen maps a Rust Result to
    // returnType "LogosResult", which the host marshals to null in the UI; a
    // plain String maps to QString and passes through. Errors are {"error":...}.
    fn produce_auth(&mut self, args_json: String) -> String {
        dispatch_produce(&args_json, &self.registry)
    }
    fn card_status(&mut self) -> String {
        card_status_impl().unwrap_or_else(|e| json!({ "present": false, "error": e }).to_string())
    }
}

// Poll the reader for card presence via SCardGetStatusChange — no card session,
// so it never resets the card (unlike connect+select at poll rate).
fn card_status_impl() -> Result<String, String> {
    let present = reader_card_present()?;
    Ok(json!({ "present": present }).to_string())
}

#[no_mangle]
pub extern "Rust" fn logos_module_install() {
    install::<KeycardCapture>();
}
